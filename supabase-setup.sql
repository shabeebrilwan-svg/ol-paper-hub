-- Run in Supabase SQL Editor for your new project.
-- Admin users must be added manually after creating an Auth user; see README.
create table if not exists public.papers (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text not null default 'Mathematics',
  file_path text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.papers enable row level security;
alter table public.admin_users enable row level security;
grant select on public.papers to anon, authenticated;
grant insert, delete on public.papers to authenticated;
grant select on public.admin_users to authenticated;
-- SECURITY DEFINER helper avoids recursive admin_users RLS checks.
create or replace function public.is_paper_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.admin_users where user_id = auth.uid()) $$;
revoke all on function public.is_paper_admin() from public;
grant execute on function public.is_paper_admin() to anon, authenticated;
-- Admins can read the whitelist; student users cannot.
create policy "admin can read roster" on public.admin_users for select to authenticated using (public.is_paper_admin());
create policy "public can read papers" on public.papers for select to anon, authenticated using (true);
create policy "admins can add papers" on public.papers for insert to authenticated with check (public.is_paper_admin());
create policy "admins can delete papers" on public.papers for delete to authenticated using (public.is_paper_admin());
insert into storage.buckets (id,name,public) values ('papers','papers',false) on conflict (id) do nothing;
create policy "public can read paper files" on storage.objects for select to anon, authenticated using (bucket_id='papers');
create policy "admins can upload paper files" on storage.objects for insert to authenticated with check (bucket_id='papers' and public.is_paper_admin());
create policy "admins can delete paper files" on storage.objects for delete to authenticated using (bucket_id='papers' and public.is_paper_admin());
